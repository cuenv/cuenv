#[test]
fn resource_package_follows_the_field_rules() {
    let types = generated();
    assert_eq!(types.resource_types, ["example_empty", "example_pet"]);
    let pet = types
        .files
        .get(Path::new("resources/example_pet/resource.cue"))
        .unwrap();
    let expected = r#"// Code generated by cuenv. DO NOT EDIT.
//
// Types for the example_pet resource of registry.terraform.io/acme/example-cloud 1.2.3,
// generated from the provider's schema. Regenerate them with
// `cuenv sync infrastructure`.

package example_pet

import "list"

// #Resource declares a managed resource of type example_pet.
#Resource: {
	type: "example_pet"
	configuration: #Configuration
	outputs: #Outputs
	...
}

#Configuration: {
	keepers?: {[string]: string | #Secret}
	// The length (in words) of the pet name.
	length?: number
	// Deprecated: Use `separator`.
	prefix?: string | #Secret
	rule!: [...{
		"for"?: {
			cidr!: string | #Secret
			ports!: [number, number]
		}
		port!: number
	}] & list.MinItems(1) & list.MaxItems(3)
	// The provider chooses a value when this is not set.
	separator?: string | #Secret
	// Write-only: requires a secret; bump the companion version manually.
	token?: #Value & #WriteOnly
}

// #Outputs contains selectable top-level scalar provider outputs.
#Outputs: {
	id: string
	length: number
	prefix: string
	// Sensitive: plans mask receiving arguments; strings of at least four characters are redacted.
	secret: string
	separator: string
}

// #Secret is a cuenv secret, such as `schema.#OnePasswordRef & {ref: "..."}`.
// cuenv resolves it only when the configuration reaches the provider,
// never through CUE. Ordinary secret arguments are sensitive and stored;
// write-only arguments are shown as (write-only) and stay out of state.
#Secret: {
	resolver!: string & !=""
	...
}

#Value: string | #Secret
#WriteOnly: #Secret & {writeOnly: true}
"#;
    assert_eq!(pet, expected);
    let empty = types
        .files
        .get(Path::new("resources/example_empty/resource.cue"))
        .unwrap();
    assert!(empty.contains("#Configuration: {}\n"), "{empty}");
    assert!(empty.ends_with("#Outputs: {\n}\n"), "{empty}");
    assert!(!empty.contains("#Secret"), "{empty}");
    assert!(!empty.contains("import"), "{empty}");
}

#[test]
fn only_resource_and_data_source_strings_accept_a_secret() {
    let types = generated();
    let provider = &types.files[Path::new("provider.cue")];
    assert!(!provider.contains("#Secret"), "{provider}");

    let mut block = Block::default();
    for (name, value_type) in [
        ("listed", Type::List(Box::new(Type::String))),
        ("unordered", Type::Set(Box::new(Type::String))),
        (
            "unordered_objects",
            Type::Set(Box::new(Type::Object(BTreeMap::from([(
                "token".to_string(),
                Type::String,
            )])))),
        ),
    ] {
        block
            .attributes
            .insert(name.to_string(), attribute(value_type, Presence::Optional));
    }
    block.attributes.insert(
        "nested_unordered".into(),
        Attribute {
            nested: Some(NestedAttributes {
                attributes: BTreeMap::from([(
                    "token".to_string(),
                    attribute(Type::String, Presence::Required),
                )]),
                nesting: Nesting::Set,
            }),
            ..attribute(Type::Dynamic, Presence::Optional)
        },
    );
    block.blocks.insert(
        "unordered_block".into(),
        NestedBlock {
            block: Block {
                attributes: BTreeMap::from([(
                    "token".to_string(),
                    attribute(Type::String, Presence::Required),
                )]),
                ..Block::default()
            },
            nesting: Nesting::Set,
            minimum_items: 0,
            maximum_items: 0,
        },
    );
    let mut package = Package::with_secrets("x 1.0.0", "a test", PackageKind::Resource);
    package.configuration(&block);
    assert_eq!(
        package.body,
        "#Configuration: {\n\tlisted?: [...string | #Secret]\n\tnested_unordered?: [...{\n\t\ttoken!: string\n\t}]\n\tunordered?: [...string]\n\tunordered_block?: [...{\n\t\ttoken!: string\n\t}]\n\tunordered_objects?: [...{\n\t\ttoken!: string\n\t}]\n}\n"
    );
}

