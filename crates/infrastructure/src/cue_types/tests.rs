use super::*;
use crate::schema::{ProviderCapabilities, Schema};
use std::collections::HashMap;

fn attribute(value_type: Type, presence: Presence) -> Attribute {
    Attribute {
        value_type,
        nested: None,
        presence,
        sensitive: false,
        write_only: false,
        documentation: Documentation::default(),
    }
}

fn described(mut attribute: Attribute, description: &str) -> Attribute {
    attribute.documentation.description = description.to_string();
    attribute
}

fn pet_block() -> Block {
    let mut block = Block::default();
    block
        .attributes
        .insert("id".into(), attribute(Type::String, Presence::Computed));
    block.attributes.insert(
        "length".into(),
        described(
            attribute(Type::Number, Presence::Optional),
            "The length (in words) of the pet name.",
        ),
    );
    block.attributes.insert(
        "keepers".into(),
        attribute(Type::Map(Box::new(Type::String)), Presence::Optional),
    );
    block.attributes.insert(
        "separator".into(),
        attribute(Type::String, Presence::OptionalComputed),
    );
    let mut token = attribute(Type::String, Presence::Optional);
    token.write_only = true;
    block.attributes.insert("token".into(), token);
    let mut prefix = attribute(Type::String, Presence::Optional);
    prefix.documentation.deprecated = true;
    prefix.documentation.deprecation_message = "Use `separator`.".into();
    block.attributes.insert("prefix".into(), prefix);
    let mut rule = Block::default();
    rule.attributes
        .insert("port".into(), attribute(Type::Number, Presence::Required));
    rule.attributes.insert(
        "for".into(),
        attribute(
            Type::Object(BTreeMap::from([
                ("cidr".to_string(), Type::String),
                (
                    "ports".to_string(),
                    Type::Tuple(vec![Type::Number, Type::Number]),
                ),
            ])),
            Presence::Optional,
        ),
    );
    block.blocks.insert(
        "rule".into(),
        NestedBlock {
            block: rule,
            nesting: Nesting::List,
            minimum_items: 1,
            maximum_items: 3,
        },
    );
    block
}

fn provider_schema() -> ProviderSchema {
    let mut provider = Block::default();
    let mut secret = attribute(Type::String, Presence::Required);
    secret.sensitive = true;
    provider.attributes.insert("api_key".into(), secret);
    ProviderSchema {
        provider: Schema {
            version: 0,
            block: provider,
        },
        resources: HashMap::from([
            (
                "example_pet".to_string(),
                Schema {
                    version: 1,
                    block: pet_block(),
                },
            ),
            (
                "example_empty".to_string(),
                Schema {
                    version: 0,
                    block: Block::default(),
                },
            ),
        ]),
        capabilities: ProviderCapabilities::default(),
    }
}

fn source() -> ProviderSource {
    ProviderSource::parse("acme/example-cloud").unwrap()
}

fn generated() -> GeneratedTypes {
    let source = source();
    render(
        &provider_schema(),
        ProviderRelease {
            source: &source,
            version: "1.2.3",
        },
    )
    .unwrap()
}

#[test]
fn provider_package_binds_source_version_and_digest() {
    let types = generated();
    assert_eq!(
        types.import_path,
        "registry.terraform.io/acme/example-cloud"
    );
    assert_eq!(types.package_name, "example_cloud_provider");
    assert_eq!(
        types.directory,
        Path::new("cue.mod/gen/registry.terraform.io/acme/example-cloud")
    );
    let provider = types.files.get(Path::new("provider.cue")).unwrap();
    let expected = format!(
        r#"// Code generated by cuenv. DO NOT EDIT.
//
// Types for the provider's configuration block of registry.terraform.io/acme/example-cloud 1.2.3,
// generated from the provider's schema. Regenerate them with
// `cuenv sync infrastructure`.

package example_cloud_provider

// #Provider declares the provider at exactly the version and schema
// these types were generated from.
#Provider: {{
	source: "registry.terraform.io/acme/example-cloud"
	version: "1.2.3"
	schemaDigest: "{digest}"
	configuration: #Configuration
}}

#Configuration: {{
	// Sensitive: plans show it as (sensitive).
	api_key!: string
}}
"#,
        digest = types.schema_digest
    );
    assert_eq!(provider, &expected);
}

#[test]
fn resource_package_follows_the_field_rules() {
    let types = generated();
    assert_eq!(types.resource_types, ["example_empty", "example_pet"]);
    let pet = types
        .files
        .get(Path::new("resources/example_pet/resource.cue"))
        .unwrap();
    let expected = r#"// Code generated by cuenv. DO NOT EDIT.
//
// Types for the example_pet resource of registry.terraform.io/acme/example-cloud 1.2.3,
// generated from the provider's schema. Regenerate them with
// `cuenv sync infrastructure`.

package example_pet

import "list"

// #Resource declares a managed resource of type example_pet.
#Resource: {
	type: "example_pet"
	configuration: #Configuration
	...
}

#Configuration: {
	keepers?: {[string]: string}
	// The length (in words) of the pet name.
	length?: number
	// Deprecated: Use `separator`.
	prefix?: string
	rule!: [...{
		"for"?: {
			cidr!: string
			ports!: [number, number]
		}
		port!: number
	}] & list.MinItems(1) & list.MaxItems(3)
	// The provider chooses a value when this is not set.
	separator?: string
}
"#;
    assert_eq!(pet, expected);
    let empty = types
        .files
        .get(Path::new("resources/example_empty/resource.cue"))
        .unwrap();
    assert!(empty.ends_with("#Configuration: {}\n"), "{empty}");
    assert!(!empty.contains("import"), "{empty}");
}

#[test]
fn import_lines_qualify_provider_packages() {
    let types = generated();
    assert_eq!(
        types.provider_import(),
        r#""registry.terraform.io/acme/example-cloud:example_cloud_provider""#
    );
    assert_eq!(
        types.resource_import("example_pet"),
        r#""registry.terraform.io/acme/example-cloud/resources/example_pet""#
    );
    let random = ProviderSource::parse("hashicorp/random").unwrap();
    let types = render(
        &provider_schema(),
        ProviderRelease {
            source: &random,
            version: "3.9.1",
        },
    )
    .unwrap();
    assert_eq!(
        types.provider_import(),
        r#""registry.terraform.io/hashicorp/random:random_provider""#
    );
}

