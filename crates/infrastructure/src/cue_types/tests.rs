#[test]
fn descriptions_do_not_change_the_digest_but_shapes_do() {
    let schema = provider_schema();
    let digest = schema_digest(&schema);
    assert!(digest.starts_with("sha256:"), "{digest}");
    assert_eq!(digest.len(), "sha256:".len() + 64);
    assert_eq!(
        digest,
        schema_digest(&provider_schema()),
        "digest is stable"
    );

    let mut described = provider_schema();
    if let Some(pet) = described.resources.get_mut("example_pet") {
        pet.block.documentation.description = "A pet.".into();
        pet.version = 7;
        if let Some(length) = pet.block.attributes.get_mut("length") {
            length.documentation.description = "Something else.".into();
        }
    }
    assert_eq!(digest, schema_digest(&described));

    let mut required = provider_schema();
    if let Some(length) = required
        .resources
        .get_mut("example_pet")
        .and_then(|pet| pet.block.attributes.get_mut("length"))
    {
        length.presence = Presence::Required;
    }
    assert_ne!(digest, schema_digest(&required));

    let mut fewer = provider_schema();
    fewer.resources.remove("example_empty");
    assert_ne!(digest, schema_digest(&fewer));
}

#[test]
fn provider_text_cannot_escape_a_comment() {
    let documentation = Documentation {
        description: "\n\nFirst line\r\nSecond\u{1b}[31m line\n\n".into(),
        deprecated: true,
        deprecation_message: String::new(),
    };
    assert_eq!(
        documentation_lines(&documentation, &["Note."]),
        ["First line", "Second[31m line", "", "Deprecated.", "Note."]
    );
}

#[test]
fn labels_that_are_not_plain_identifiers_are_quoted() {
    assert_eq!(label("name"), "name");
    assert_eq!(label("if"), "\"if\"");
    assert_eq!(label("_hidden"), "\"_hidden\"");
    assert_eq!(label("9lives"), "\"9lives\"");
    assert_eq!(label("with-dash"), "\"with-dash\"");
    // A `number` field would shadow the predeclared type `number`.
    assert_eq!(label("number"), "\"number\"");
    assert_eq!(label("list"), "\"list\"");
}

#[test]
fn protocol_six_nested_attributes_are_rendered_recursively() {
    let mut block = Block::default();
    let mut nested = BTreeMap::new();
    nested.insert(
        "name".to_string(),
        attribute(Type::String, Presence::Required),
    );
    nested.insert(
        "id".to_string(),
        attribute(Type::String, Presence::Computed),
    );
    block.attributes.insert(
        "tags".into(),
        Attribute {
            nested: Some(NestedAttributes {
                attributes: nested,
                nesting: Nesting::Map,
            }),
            ..attribute(Type::Dynamic, Presence::Optional)
        },
    );
    let mut package = Package::new("x 1.0.0", "a test");
    package.configuration(&block);
    assert_eq!(
        package.body,
        "#Configuration: {\n\ttags?: {[string]: {\n\t\tname!: string\n\t}}\n}\n"
    );
}
