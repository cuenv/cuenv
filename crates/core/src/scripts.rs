//! Scripts: files of a project's `scriptDirs` that run as tasks.
//!
//! cuenv writes the scripts it finds to `scripts.gen.cue` beside the project
//! (see [`render`]), so that CUE can reference them as `scripts.<name>` and
//! the project can add to them by name. Evaluation then turns each entry of
//! `scripts` into a task of the same name ([`into_tasks`]).

mod scan;

use std::collections::BTreeMap;
use std::fmt::Write as _;
use std::path::{Path, PathBuf};

use serde::Deserialize;
use serde_json::{Map, Value, json};

pub use scan::{Detected, Found, Scan, ScriptDirectory, scan, supported};

/// The file cuenv writes a project's scripts to.
pub const GENERATED_FILE: &str = "scripts.gen.cue";

const HEADER: &str = "// Code generated by cuenv from scriptDirs. DO NOT EDIT.\n\
// Any cuenv command rewrites this file when the scripts change.\n";

/// Where the generated file of the project in `project_dir` lives.
#[must_use]
pub fn generated_path(project_dir: &Path) -> PathBuf {
    project_dir.join(GENERATED_FILE)
}

/// The `scriptDirs` of an evaluated project; `None` when it declares none.
#[must_use]
pub fn directories(project: &Value) -> Option<Vec<ScriptDirectory>> {
    let declared = project.get("scriptDirs")?;
    match serde_json::from_value(declared.clone()) {
        Ok(directories) => Some(directories),
        Err(error) => {
            tracing::warn!(%error, "scriptDirs could not be read");
            None
        }
    }
}

/// The generated file for `scan`, in CUE package `package`.
#[must_use]
pub fn render(package: &str, scan: &Scan) -> String {
    format!("{HEADER}\npackage {package}\n\n{}", render_body(scan))
}

/// Everything of the generated file after its `package` clause, which is all
/// that tells two scans apart.
fn render_body(scan: &Scan) -> String {
    if scan.scripts.is_empty() {
        return "scripts: {}\n".to_string();
    }
    // Labels padded to one width, as `cue fmt` aligns the values of
    // consecutive fields, so that formatting leaves the file unchanged.
    let labels: Vec<String> = scan.scripts.keys().map(|name| label(name)).collect();
    let width = labels.iter().map(String::len).max().unwrap_or(0);
    let mut body = String::from("scripts: {\n");
    for (label, found) in labels.iter().zip(scan.scripts.values()) {
        let file = quote(&found.file);
        let fields = match &found.detected {
            Detected::Program(program) => {
                format!("file: {file}, interpreter: *{} | _", quote(program))
            }
            Detected::Unsupported(program) => {
                format!("file: {file}, unsupported: {}", quote(program))
            }
            Detected::Ambiguous => format!("file: {file}"),
        };
        let _ = writeln!(
            body,
            "\t{label}:{:pad$} {{{fields}}}",
            "",
            pad = width - label.len()
        );
    }
    body.push_str("}\n");
    body
}

/// A CUE label for a script name: bare when it is a plain identifier.
fn label(name: &str) -> String {
    let mut bytes = name.bytes();
    let plain = bytes
        .next()
        .is_some_and(|first| first.is_ascii_alphabetic())
        && bytes.all(|byte| byte.is_ascii_alphanumeric() || byte == b'_');
    if plain { name.to_string() } else { quote(name) }
}

fn quote(text: &str) -> String {
    serde_json::to_string(text).unwrap_or_else(|_| format!("\"{text}\""))
}

/// How the generated file of a project differs from its scripts.
#[derive(Debug, Clone, PartialEq, Eq)]
pub enum Drift {
    /// The file matches.
    None,
    /// The file is missing or does not list the scripts found.
    Stale,
    /// The project lists no `scriptDirs` but the file is still there.
    Orphaned,
}

/// Compare the generated file in `project_dir` with a fresh scan.
#[must_use]
pub fn drift(project_dir: &Path, directories: Option<&[ScriptDirectory]>) -> (Drift, Scan) {
    let path = generated_path(project_dir);
    let existing = std::fs::read_to_string(&path).ok();
    let Some(directories) = directories else {
        let drift = if existing.is_some() {
            Drift::Orphaned
        } else {
            Drift::None
        };
        return (drift, Scan::default());
    };
    let scan = scan(project_dir, directories);
    let expected = render_body(&scan);
    let current = existing.as_deref().and_then(body_after_package);
    let drift = if current == Some(expected.as_str()) {
        Drift::None
    } else {
        Drift::Stale
    };
    (drift, scan)
}

/// The package an existing generated file declares, which a rewrite keeps.
#[must_use]
pub fn package_of(text: &str) -> Option<&str> {
    let start = text.find("\npackage ")? + "\npackage ".len();
    let name = text[start..].lines().next()?.trim();
    (!name.is_empty()).then_some(name)
}

/// The text after the `package` clause and its blank line.
fn body_after_package(text: &str) -> Option<&str> {
    let start = text.find("\npackage ")? + 1;
    let after = &text[start..];
    let line_end = after.find('\n')?;
    Some(after[line_end + 1..].trim_start_matches('\n'))
}

/// One entry of an evaluated `scripts` field.
#[derive(Debug, Deserialize)]
#[serde(rename_all = "camelCase")]
struct ScriptEntry {
    file: String,
    #[serde(default)]
    interpreter: Option<String>,
    #[serde(default)]
    unsupported: Option<String>,
    #[serde(default)]
    description: Option<String>,
    #[serde(flatten)]
    rest: Map<String, Value>,
}

/// Fields of a script entry a task takes over unchanged.
const TASK_FIELDS: [&str; 8] = [
    "params",
    "dependsOn",
    "hermetic",
    "inputs",
    "outputs",
    "cache",
    "labels",
    "cuenvRef",
];

/// A script converted to a task, or why it could not be.
type Converted = Result<Map<String, Value>, String>;

/// Turn each entry of the project's `scripts` into a task of the same name,
/// and record each problem against the task it concerns.
///
/// `instance` is the project's directory relative to the module root, with
/// `/` separators, empty for the root.
pub(crate) fn into_tasks(
    value: &mut Value,
    instance: &str,
    problems: &mut BTreeMap<String, Vec<String>>,
) {
    let Some(root) = value.as_object_mut() else {
        return;
    };
    let Some(Value::Object(scripts)) = root.get("scripts") else {
        return;
    };
    let directories: Vec<ScriptDirectory> = root
        .get("scriptDirs")
        .and_then(|declared| serde_json::from_value(declared.clone()).ok())
        .unwrap_or_default();
    let converted: Vec<(String, Converted)> = scripts
        .iter()
        .map(|(name, entry)| {
            let task = serde_json::from_value::<ScriptEntry>(entry.clone())
                .map_err(|error| format!("script `{name}` could not be read: {error}"))
                .map(|entry| {
                    task_value(
                        name,
                        &entry,
                        &Origin {
                            directories: &directories,
                            instance,
                        },
                    )
                });
            (name.clone(), task)
        })
        .collect();
    let tasks = root
        .entry("tasks")
        .or_insert_with(|| Value::Object(Map::new()));
    let Value::Object(tasks) = tasks else {
        return;
    };
    for (name, task) in converted {
        let task = match task {
            Ok(task) => task,
            Err(problem) => {
                record(problems, &name, problem);
                continue;
            }
        };
        if tasks.contains_key(&name) {
            record(
                problems,
                &name,
                format!(
                    "`{name}` is both a task and a script; rename the task, or the script with `rename` in `scriptDirs`"
                ),
            );
            continue;
        }
        if let Some(problem) = problem(&name, &task) {
            record(problems, &name, problem);
        }
        tasks.insert(name, Value::Object(task));
    }
}

fn record(problems: &mut BTreeMap<String, Vec<String>>, name: &str, problem: String) {
    problems.entry(name.to_string()).or_default().push(problem);
}

/// Why a converted script cannot run, if it cannot.
fn problem(name: &str, task: &Map<String, Value>) -> Option<String> {
    let script = task.get("_cuenvScript")?;
    let file = script.get("path")?.as_str()?;
    let interpreter = script.get("interpreter")?.as_str()?;
    if let Some(program) = script.get("unsupported").and_then(Value::as_str) {
        // Recorded only when the project set no interpreter of its own.
        return Some(format!(
            "`{file}` runs with `{program}`, which cuenv does not run scripts with; set `scripts.{name}.interpreter` to bash, sh, fish, nu, python or bun, or exclude the file"
        ));
    }
    if interpreter.is_empty() {
        return Some(format!(
            "the interpreter of `{file}` is ambiguous: give it a shebang such as `#!/usr/bin/env bash`, or set `scripts.{name}.interpreter`"
        ));
    }
    None
}

/// Where the scripts of a project come from.
struct Origin<'project> {
    directories: &'project [ScriptDirectory],
    /// The project's directory relative to the module root.
    instance: &'project str,
}

/// The task a script runs as. Its own fields win over its directory's.
fn task_value(name: &str, entry: &ScriptEntry, origin: &Origin<'_>) -> Map<String, Value> {
    let Origin {
        directories,
        instance,
    } = *origin;
    let directory = directories
        .iter()
        .find(|directory| {
            let path = directory
                .path
                .trim_start_matches("./")
                .trim_end_matches('/');
            Path::new(&entry.file).parent() == Some(Path::new(path))
        })
        .cloned()
        .unwrap_or_default();
    let interpreter = entry.interpreter.clone().unwrap_or_default();
    // A script that cannot run still needs a command to be read; its problem
    // is recorded and stops it before anything starts.
    let (command, args) = if interpreter.is_empty() {
        (entry.file.clone(), Vec::new())
    } else {
        (interpreter.clone(), vec![entry.file.clone()])
    };
    let unsupported = if entry.interpreter.is_some() {
        None
    } else {
        entry.unsupported.clone()
    };
    let source_file = if instance.is_empty() {
        entry.file.clone()
    } else {
        format!("{instance}/{}", entry.file)
    };
    let description = entry.description.clone().unwrap_or_else(|| {
        if interpreter.is_empty() {
            format!("Script {}", entry.file)
        } else {
            format!("Script {} ({interpreter})", entry.file)
        }
    });
    let mut task = Map::new();
    task.insert("command".into(), json!(command));
    task.insert("args".into(), json!(args));
    task.insert("description".into(), json!(description));
    task.insert(
        "hermetic".into(),
        directory.hermetic.clone().unwrap_or(Value::Bool(false)),
    );
    if let Some(outputs) = &directory.outputs {
        task.insert("outputs".into(), outputs.clone());
    }
    if let Some(cache) = &directory.cache {
        task.insert("cache".into(), cache.clone());
    }
    for field in TASK_FIELDS {
        if let Some(value) = entry.rest.get(field) {
            task.insert(field.into(), value.clone());
        }
    }
    // The script is always an input, ahead of its own or its directory's.
    let extra = entry
        .rest
        .get("inputs")
        .and_then(Value::as_array)
        .cloned()
        .unwrap_or_else(|| directory.inputs.clone());
    let mut inputs = vec![json!(entry.file)];
    inputs.extend(extra);
    task.insert("inputs".into(), Value::Array(inputs));
    // Scripts run from the project directory, like a task declared there.
    task.insert(
        "dir".into(),
        json!({"from": "module", "path": if instance.is_empty() { "." } else { instance }}),
    );
    task.insert(
        "_source".into(),
        json!({"file": source_file, "line": 1, "column": 1}),
    );
    task.insert(
        "_cuenvScript".into(),
        json!({"name": name, "path": entry.file, "interpreter": interpreter, "unsupported": unsupported}),
    );
    task
}

