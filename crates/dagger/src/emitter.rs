//! Dagger 1.0 workspace & Dang DSL emitter (Phase 2).
//!
//! Generates:
//! - `dagger.toml`
//! - `.dagger/modules/<module_name>/dagger-module.toml`
//! - `.dagger/modules/<module_name>/main.dang`
//!
//! Implements [`cuenv_ci::emitter::Emitter`] for single-file export
//! (`cuenv ci --export dagger`) and [`DaggerWorkspaceEmitter::emit_workspace`]
//! for multi-file workspace sync (`cuenv sync ci`).

use std::collections::HashMap;
use std::fmt::Write as _;
use std::path::PathBuf;

use cuenv_ci::emitter::{Emitter, EmitterResult};
use cuenv_ci::ir::{IntermediateRepresentation, Task as IrTask};
use cuenv_core::ci::PipelineMode;
use cuenv_core::environment::EnvValue;
use cuenv_core::manifest::{Entrypoint, Runtime, Service};

use crate::config::DaggerCiConfig;

const GENERATED_HEADER: &str = "# Code generated by cuenv. DO NOT EDIT.\n";

/// A single generated file relative to the repository root.
#[derive(Debug, Clone, PartialEq, Eq)]
pub struct EmittedFile {
    /// Path relative to the repository root.
    pub relative_path: PathBuf,
    /// Generated file contents.
    pub content: String,
}

/// Inputs for emitting a full Dagger 1.0 workspace (`cuenv sync ci`).
#[derive(Debug, Clone, Copy)]
pub struct WorkspaceEmitInput<'input> {
    /// Compiled CI pipeline IRs targeting the `"dagger"` provider.
    pub pipelines: &'input [IntermediateRepresentation],
    /// Project services to optionally expose as `@up` functions in `main.dang`.
    pub services: &'input HashMap<String, Service>,
}

/// Emits Dagger 1.0 workspace files (`dagger.toml`, `dagger-module.toml`, `main.dang`).
#[derive(Debug, Clone, Default)]
pub struct DaggerWorkspaceEmitter {
    /// Provider configuration from `ci.providerConfig.dagger`.
    pub config: DaggerCiConfig,
}

impl DaggerWorkspaceEmitter {
    /// Create a new emitter with the given [`DaggerCiConfig`].
    #[must_use]
    pub const fn new(config: DaggerCiConfig) -> Self {
        Self { config }
    }

    /// Emit all Dagger 1.0 workspace files for one or more pipelines.
    ///
    /// # Errors
    ///
    /// Returns [`cuenv_ci::emitter::EmitterError`] if formatting fails.
    pub fn emit_workspace(&self, input: WorkspaceEmitInput<'_>) -> EmitterResult<Vec<EmittedFile>> {
        let module_name = self.config.module_name();
        let base_dir = normalize_workspace_dir(self.config.workspace_dir());

        let dagger_toml = format!(
            "{GENERATED_HEADER}\n[toolchains.{module_name}]\nsource = \".dagger/modules/{module_name}\"\n"
        );
        let module_toml = format!(
            "{GENERATED_HEADER}\nname = \"{module_name}\"\n\n[runtime]\nsource = \"dang\"\n"
        );
        let main_dang = self.render_dang_module(input.pipelines, input.services);

        let files = vec![
            EmittedFile {
                relative_path: join_rel(&base_dir, "dagger.toml"),
                content: dagger_toml,
            },
            EmittedFile {
                relative_path: join_rel(
                    &base_dir,
                    &format!(".dagger/modules/{module_name}/dagger-module.toml"),
                ),
                content: module_toml,
            },
            EmittedFile {
                relative_path: join_rel(
                    &base_dir,
                    &format!(".dagger/modules/{module_name}/main.dang"),
                ),
                content: main_dang,
            },
        ];

        Ok(files)
    }

    fn render_dang_module(
        &self,
        pipelines: &[IntermediateRepresentation],
        services: &HashMap<String, Service>,
    ) -> String {
        let mut out = String::new();
        out.push_str(GENERATED_HEADER);
        out.push_str("# Run checks with: dagger check\n");
        if self.config.should_emit_services() && !services.is_empty() {
            out.push_str("# Start services with: dagger start\n");
        }
        out.push('\n');

        let mut emitted_names = std::collections::HashSet::new();

        for ir in pipelines {
            match ir.pipeline.mode {
                PipelineMode::Thin => {
                    let fn_name = sanitize_dang_ident(&format!("pipeline_{}", ir.pipeline.name));
                    if emitted_names.insert(fn_name.clone()) {
                        self.append_thin_check(&mut out, &fn_name, ir);
                    }
                }
                PipelineMode::Expanded => {
                    for task in ir.regular_tasks() {
                        let fn_name = sanitize_dang_ident(&task.id);
                        if emitted_names.insert(fn_name.clone()) {
                            self.append_expanded_check(&mut out, &fn_name, task, ir);
                        }
                    }
                }
            }
        }

        if self.config.should_emit_services() {
            let mut sorted_services: Vec<(&String, &Service)> = services.iter().collect();
            sorted_services.sort_by_key(|(name, _)| *name);
            for (name, service) in sorted_services {
                let fn_name = sanitize_dang_ident(name);
                if emitted_names.insert(fn_name.clone()) {
                    self.append_up_service(&mut out, &fn_name, name, service);
                }
            }
        }

        out
    }

    fn append_thin_check(&self, out: &mut String, fn_name: &str, ir: &IntermediateRepresentation) {
        let image = self.config.default_image();
        let _ = writeln!(out, "@check");
        let _ = writeln!(out, "pub {fn_name}(ws: Workspace!): Void {{");
        let _ = writeln!(out, "  container");
        let _ = writeln!(out, "    .from(\"{}\")", escape_dang_str(image));
        let _ = writeln!(
            out,
            "    .withMountedDirectory(\"/work\", ws.directory(\".\"))"
        );
        let _ = writeln!(out, "    .withWorkdir(\"/work\")");
        let _ = writeln!(
            out,
            "    .withExec([\"cuenv\", \"ci\", \"--pipeline\", \"{}\"])",
            escape_dang_str(&ir.pipeline.name)
        );
        let _ = writeln!(out, "    .sync");
        let _ = writeln!(out, "}}\n");
    }

    fn append_expanded_check(
        &self,
        out: &mut String,
        fn_name: &str,
        task: &IrTask,
        ir: &IntermediateRepresentation,
    ) {
        let image = resolve_ir_image(task, ir, self.config.default_image());
        let mut params = vec!["ws: Workspace!".to_string()];
        for secret_name in task.secrets.keys() {
            let param = sanitize_dang_ident(secret_name);
            params.push(format!("{param}: Secret!"));
        }

        let _ = writeln!(out, "@check");
        let _ = writeln!(out, "pub {fn_name}({}): Void {{", params.join(", "));
        let _ = writeln!(out, "  let src = {}", render_ws_directory(&task.inputs));
        let _ = writeln!(out, "  container");
        let _ = writeln!(out, "    .from(\"{}\")", escape_dang_str(&image));
        let _ = writeln!(out, "    .withMountedDirectory(\"/work\", src)");
        let _ = writeln!(out, "    .withWorkdir(\"/work\")");

        for (k, v) in &task.env {
            let _ = writeln!(
                out,
                "    .withEnvVariable(\"{}\", \"{}\")",
                escape_dang_str(k),
                escape_dang_str(v)
            );
        }

        for secret_name in task.secrets.keys() {
            let param = sanitize_dang_ident(secret_name);
            let _ = writeln!(
                out,
                "    .withSecretVariable(\"{}\", {param})",
                escape_dang_str(secret_name)
            );
        }

        if let Some(services) = task
            .provider_hints
            .as_ref()
            .and_then(|hints| hints.get("dagger"))
            .and_then(|dagger| dagger.get("services"))
            .and_then(serde_json::Value::as_array)
        {
            for svc in services.iter().filter_map(serde_json::Value::as_str) {
                let svc_fn = sanitize_dang_ident(svc);
                let _ = writeln!(
                    out,
                    "    .withServiceBinding(\"{}\", {svc_fn}())",
                    escape_dang_str(svc)
                );
            }
        }

        let exec_args = if task.shell {
            let joined = task.command.join(" ");
            vec!["sh".to_string(), "-euc".to_string(), joined]
        } else if task.command.is_empty() {
            vec!["true".to_string()]
        } else {
            task.command.clone()
        };
        let rendered_args: Vec<String> = exec_args
            .iter()
            .map(|arg| format!("\"{}\"", escape_dang_str(arg)))
            .collect();
        let _ = writeln!(out, "    .withExec([{}])", rendered_args.join(", "));
        let _ = writeln!(out, "    .sync");
        let _ = writeln!(out, "}}\n");
    }

    fn append_up_service(
        &self,
        out: &mut String,
        fn_name: &str,
        service_name: &str,
        service: &Service,
    ) {
        let image = match service.runtime.as_ref() {
            Some(Runtime::Container(c)) => c.image.as_str(),
            Some(Runtime::Dagger(d)) => d.image.as_deref().unwrap_or(self.config.default_image()),
            _ => self.config.default_image(),
        };

        let _ = writeln!(out, "@up");
        let _ = writeln!(out, "# Service '{service_name}' exposed for `dagger start`");
        let _ = writeln!(out, "pub {fn_name}(): Service! {{");
        let _ = writeln!(out, "  container");
        let _ = writeln!(out, "    .from(\"{}\")", escape_dang_str(image));

        let mut sorted_env: Vec<(&String, &EnvValue)> = service.env.iter().collect();
        sorted_env.sort_by_key(|(k, _)| *k);
        for (k, v) in sorted_env {
            let rendered = match v {
                EnvValue::String(s) => Some(s.clone()),
                EnvValue::Int(i) => Some(i.to_string()),
                EnvValue::Bool(b) => Some(b.to_string()),
                _ => None,
            };
            if let Some(val) = rendered {
                let _ = writeln!(
                    out,
                    "    .withEnvVariable(\"{}\", \"{}\")",
                    escape_dang_str(k),
                    escape_dang_str(&val)
                );
            }
        }

        for port in &service.ports {
            let _ = writeln!(out, "    .withExposedPort({})", port.port);
        }

        let args = match &service.entrypoint {
            Entrypoint::Command(cmd) if !cmd.command.is_empty() => {
                let mut v = vec![cmd.command.clone()];
                for arg in &cmd.args {
                    v.push(arg.as_str().map_or_else(|| arg.to_string(), str::to_string));
                }
                v
            }
            Entrypoint::Script(script) => {
                vec!["sh".to_string(), "-euc".to_string(), script.script.clone()]
            }
            _ => Vec::new(),
        };

        if args.is_empty() {
            let _ = writeln!(out, "    .asService");
        } else {
            let rendered: Vec<String> = args
                .iter()
                .map(|a| format!("\"{}\"", escape_dang_str(a)))
                .collect();
            let _ = writeln!(out, "    .asService(args: [{}])", rendered.join(", "));
        }
        let _ = writeln!(out, "}}\n");
    }
}

impl Emitter for DaggerWorkspaceEmitter {
    fn emit_thin(&self, ir: &IntermediateRepresentation) -> EmitterResult<String> {
        let mut thin_ir = ir.clone();
        thin_ir.pipeline.mode = PipelineMode::Thin;
        Ok(self.render_dang_module(&[thin_ir], &HashMap::new()))
    }

    fn emit_expanded(&self, ir: &IntermediateRepresentation) -> EmitterResult<String> {
        let mut expanded_ir = ir.clone();
        expanded_ir.pipeline.mode = PipelineMode::Expanded;
        Ok(self.render_dang_module(&[expanded_ir], &HashMap::new()))
    }

    fn format_name(&self) -> &'static str {
        "dagger"
    }

    fn file_extension(&self) -> &'static str {
        "dang"
    }
}

fn resolve_ir_image(
    task: &IrTask,
    _ir: &IntermediateRepresentation,
    default_image: &str,
) -> String {
    if let Some(image) = task
        .provider_hints
        .as_ref()
        .and_then(|hints| hints.get("dagger"))
        .and_then(|dagger| dagger.get("image"))
        .and_then(serde_json::Value::as_str)
    {
        return image.to_string();
    }
    default_image.to_string()
}

fn render_ws_directory(inputs: &[String]) -> String {
    if inputs.is_empty() {
        return "ws.directory(\".\")".to_string();
    }
    let rendered: Vec<String> = inputs
        .iter()
        .map(|p| format!("\"{}\"", escape_dang_str(p)))
        .collect();
    format!("ws.directory(\".\", include: [{}])", rendered.join(", "))
}

fn sanitize_dang_ident(raw: &str) -> String {
    let mut out = String::with_capacity(raw.len());
    for (idx, ch) in raw.chars().enumerate() {
        if ch.is_ascii_alphanumeric() || ch == '_' {
            if idx == 0 && ch.is_ascii_digit() {
                out.push('_');
            }
            out.push(ch.to_ascii_lowercase());
        } else {
            out.push('_');
        }
    }
    if out.is_empty() {
        "task".to_string()
    } else {
        out
    }
}

fn escape_dang_str(raw: &str) -> String {
    raw.replace('\\', "\\\\")
        .replace('"', "\\\"")
        .replace('\n', "\\n")
}

fn normalize_workspace_dir(raw: &str) -> PathBuf {
    let trimmed = raw.trim().trim_matches('/');
    if trimmed.is_empty() || trimmed == "." {
        PathBuf::new()
    } else {
        PathBuf::from(trimmed)
    }
}

fn join_rel(base: &std::path::Path, child: &str) -> PathBuf {
    if base.as_os_str().is_empty() {
        PathBuf::from(child)
    } else {
        base.join(child)
    }
}

#[cfg(test)]
mod tests {
    use super::*;
    use cuenv_ci::ir::{CachePolicy, SecretConfig};
    use std::collections::BTreeMap;

    fn sample_expanded_ir() -> IntermediateRepresentation {
        let mut ir = IntermediateRepresentation::new("ci");
        ir.pipeline.mode = PipelineMode::Expanded;

        let mut env = BTreeMap::new();
        env.insert("RUST_LOG".to_string(), "info".to_string());

        let mut secrets = BTreeMap::new();
        secrets.insert(
            "CARGO_REGISTRY_TOKEN".to_string(),
            SecretConfig {
                source: "env://CARGO_REGISTRY_TOKEN".to_string(),
                cache_key: false,
            },
        );

        ir.tasks.push(IrTask {
            github_task_filter: Vec::new(),
            github_permissions: BTreeMap::new(),
            github_execution: None,
            id: "test.unit".to_string(),
            runtime: None,
            command: vec!["cargo".to_string(), "test".to_string()],
            shell: false,
            env,
            secrets,
            resources: None,
            concurrency_group: None,
            inputs: vec!["src/**".to_string(), "Cargo.toml".to_string()],
            outputs: Vec::new(),
            depends_on: Vec::new(),
            cache_policy: CachePolicy::default(),
            deployment: false,
            manual_approval: false,
            matrix: None,
            artifact_downloads: Vec::new(),
            params: BTreeMap::new(),
            phase: None,
            label: None,
            priority: None,
            contributor: None,
            condition: None,
            provider_hints: Some(serde_json::json!({ "dagger": { "image": "rust:1.88" } })),
            external_dependencies: Vec::new(),
        });
        ir
    }

    #[test]
    fn emits_workspace_files_with_checks_and_up_services() {
        let ir = sample_expanded_ir();
        let pg: Service = serde_json::from_value(serde_json::json!({
            "type": "service",
            "runtime": { "type": "container", "image": "postgres:16" },
            "ports": [{ "port": 5432 }],
            "env": { "POSTGRES_PASSWORD": "dev" }
        }))
        .expect("valid service");
        let mut services = HashMap::new();
        services.insert("postgres".to_string(), pg);

        let emitter = DaggerWorkspaceEmitter::new(DaggerCiConfig {
            module_name: Some("cuenv_ci".to_string()),
            ..DaggerCiConfig::default()
        });

        let files = emitter
            .emit_workspace(WorkspaceEmitInput {
                pipelines: &[ir],
                services: &services,
            })
            .expect("emit workspace");

        assert_eq!(files.len(), 3);
        assert_eq!(files[0].relative_path, PathBuf::from("dagger.toml"));
        assert!(files[0].content.contains("[toolchains.cuenv_ci]"));
        assert_eq!(
            files[1].relative_path,
            PathBuf::from(".dagger/modules/cuenv_ci/dagger-module.toml")
        );
        assert!(files[1].content.contains("source = \"dang\""));

        let dang = &files[2].content;
        assert!(dang.contains("@check"));
        assert!(
            dang.contains("pub test_unit(ws: Workspace!, cargo_registry_token: Secret!): Void")
        );
        assert!(dang.contains("ws.directory(\".\", include: [\"src/**\", \"Cargo.toml\"])"));
        assert!(dang.contains(".from(\"rust:1.88\")"));
        assert!(
            dang.contains(".withSecretVariable(\"CARGO_REGISTRY_TOKEN\", cargo_registry_token)")
        );
        assert!(dang.contains("@up"));
        assert!(dang.contains("pub postgres(): Service!"));
        assert!(dang.contains(".withExposedPort(5432)"));
    }

    #[test]
    fn thin_mode_delegates_to_cuenv_ci() {
        let ir = IntermediateRepresentation::new("pr");
        let emitter = DaggerWorkspaceEmitter::default();
        let dang = emitter.emit_thin(&ir).expect("emit thin");
        assert!(dang.contains("@check"));
        assert!(dang.contains("pub pipeline_pr(ws: Workspace!): Void"));
        assert!(dang.contains("[\"cuenv\", \"ci\", \"--pipeline\", \"pr\"]"));
    }
}
